/**
 * تمپلیت‌های آمادهٔ پرووایدر (BYO API) — «کلید خودت را بیاور».
 * هر تمپلیت با یک کلیک فیلدهای کانفیگ یک کار را پر می‌کند؛ کاربر فقط کلید API
 * خودش (و در صورت نیاز شناسهٔ مدل) را وارد می‌کند. همهٔ فیلدها بعداً
 * قابل ویرایش‌اند — تمپلیت فقط نقطهٔ شروع است، نه قفل.
 *
 * دو خانواده تمپلیت:
 *  ۱) سازگار با OpenAI — provider برابر 'openai' (یا 'ollama'/'anthropic'/'gemini')
 *     با baseURL و مدل؛ برای چت، تصویر و TTS که موتور Atlas مستقیم صدا می‌زند.
 *  ۲) کاستوم (job ناهمزمان) — provider برابر 'custom' با CustomJobConfig؛
 *     برای APIهای ویدیو/سه‌بعدی که استاندارد OpenAI ندارند (submit → polling).
 *
 * نکتهٔ صداقت: `verified: true` یعنی baseURL و endpointها از مستندات رسمی
 * تأیید شده‌اند؛ `verified: false` یعنی مطمئن نیستیم — hint علت را می‌گوید و
 * هیچ اطلاعات غلطی گذاشته نشده. شناسهٔ دقیق مدل‌ها ممکن است عوض شود؛ hint
 * هر تمپلیت همین را یادآوری می‌کند.
 */
import {
  normalizeCustomJob,
  type CustomJobConfig,
  type ProviderKind,
  type TaskKind,
} from '@/stores/settingsStore'

/** خروجی make تمپلیت — patch آماده برای setTaskConfig. هرگز شامل کلید API نیست. */
export interface TemplatePatch {
  provider: ProviderKind
  baseURL: string
  model: string
  custom?: CustomJobConfig
}

export interface ProviderTemplate {
  id: string
  /** نام فارسی نمایشی */
  name: string
  nameEn: string
  /** برای کدام کارها مناسب است */
  tasks: TaskKind[]
  desc: string
  /** راهنمای کوتاه — تیر رایگان؟ کلید از کجا؟ */
  hint: string
  /** آیا baseURL/endpointها از داک رسمی تأیید شده‌اند */
  verified: boolean
  /** ساخت patch کانفیگ — بدون هیچ کلیدی */
  make: () => TemplatePatch
}

/** تمپلیت سازگار با OpenAI: فقط baseURL و مدل */
function openaiLike(
  provider: ProviderKind,
  baseURL: string,
  model: string,
): TemplatePatch {
  return { provider, baseURL, model }
}

/** تمپلیت کاستوم (job ناهمزمان) */
function customJob(
  model: string,
  cfg: Partial<CustomJobConfig>,
): TemplatePatch {
  return { provider: 'custom', baseURL: '', model, custom: normalizeCustomJob(cfg) }
}

